"""Offline evaluation on archives the demo never uses, against a scratch database. Writes docs/evaluation.md.

    python -m mem.evaluate          # needs the database container: docker compose up -d db
"""
import itertools
import os
import pathlib
import uuid

import psycopg

ADMIN = os.environ.get("DATABASE_URL", "postgresql://app:app-dev-only@127.0.0.1:55202/app")
os.environ["DATABASE_URL"] = ADMIN.rsplit("/", 1)[0] + "/app_eval"

from core import db  # noqa: E402

from . import api, engine, world  # noqa: E402

SEEDS = range(300, 306)


def pairs(groups):
    return {p for g in groups for p in itertools.combinations(sorted(g), 2)}


def prf(found, true):
    tp = len(found & true)
    p, r = tp / max(1, len(found)), tp / max(1, len(true))
    return p, r, 2 * p * r / max(1e-9, p + r)


def main():
    with psycopg.connect(ADMIN, autocommit=True) as c:
        c.execute("DROP DATABASE IF EXISTS app_eval WITH (FORCE)")
        c.execute("CREATE DATABASE app_eval")
    db.migrate()
    qa = {"n": 0, "restaurant": 0, "receipt": 0, "people_exact": 0, "people_tp": 0, "people_found": 0, "people_true": 0, "flat_receipt": 0, "flat_receipt5": 0, "not_found": 0, "photo_top1": 0}
    mom, day, link, naive, cui, n_art, unresolved = [set(), set()], [set(), set()], [set(), set()], [set(), set()], [0, 0], 0, 0
    for seed in SEEDS:
        w, t = world.build(seed), uuid.uuid5(uuid.NAMESPACE_DNS, f"eval-{seed}")
        arts = [{**a, "id": i} for i, a in enumerate(w["artifacts"])]
        n_art += len(arts)
        # --- pure indexing steps against the generator's truth
        idx = [i for i, a in enumerate(arts) if a["kind"] in engine.MOMENT_KINDS]
        truth = {}
        for i in idx:
            truth.setdefault(arts[i]["truth"]["event"], []).append((seed, i))
        groups = engine.moments(arts)
        mom[0] |= pairs([[(seed, i) for i in g] for g in groups])
        day[0] |= pairs([[(seed, i) for i in g] for g in engine.by_day(arts)])
        mom[1] |= pairs(truth.values())
        contact = {i: k for k, i in enumerate(i for i, a in enumerate(arts) if a["kind"] == "contact")}
        true_links = {(seed, i, p) for i in idx for p in arts[i]["truth"].get("people", [])}
        got, un = engine.people(arts, groups)
        unresolved += un
        link[0] |= {(seed, i, contact[c]) for i, c, _, _ in got if i in set(idx)}
        naive[0] |= {(seed, i, contact[c]) for i, c, _, _ in engine.people(arts, groups, naive=True)[0] if i in set(idx)}
        link[1] |= true_links
        found, _ = engine.places(arts)
        real = {(r["city"], engine.fold(r["name"])): r["cuisine"] for r in w["restaurants"]}
        cui[0] += sum(real.get(k) == p["cuisine"] for k, p in found.items())
        cui[1] += len(found)
        # --- questions, through the database exactly as the API answers them
        with db.tx() as c:
            c.execute("INSERT INTO tenants (id, name) VALUES (%s,%s)", [t, f"eval {seed}"])
        with db.tx(t) as c:
            api.store(c, t, w["artifacts"])
            api.reindex(c, t)
        for q in world.questions(w):
            with db.tx(t) as c:
                a = api.ask(c, t, q["question"])
                flat = [r["id"] for r in api.nearest(c, api.embed(c, t, q["question"]), 5, " AND a.kind = 'receipt'")]
                obj = api.nearest(c, api.embed(c, t, "photo " + q["object"]), 1, " AND a.kind = 'photo'")
            want = uuid.uuid5(t, q["receipt"])
            qa["n"] += 1
            qa["flat_receipt"] += flat[:1] == [want]
            qa["flat_receipt5"] += want in flat
            qa["photo_top1"] += bool(obj) and obj[0]["metadata"].get("tags", [""])[0] == q["object"].split()[0] and uuid.UUID(str(obj[0]["id"])) in {uuid.uuid5(t, x["checksum"]) for x in w["artifacts"] if x["truth"].get("object") == q["object"]}
            if a["status"] != "answered":
                qa["not_found"] += 1
                qa["people_true"] += len(q["people"])
                continue
            names = {p["name"] for p in a["people"]}
            qa["restaurant"] += a["restaurant"]["name"].lower() == q["restaurant"].lower()
            qa["receipt"] += bool(a["receipt"]) and a["receipt"]["id"] == want
            qa["people_exact"] += names == q["people"]
            qa["people_tp"] += len(names & q["people"])
            qa["people_found"] += len(names)
            qa["people_true"] += len(q["people"])
    db.close()
    with psycopg.connect(ADMIN, autocommit=True) as c:
        c.execute("DROP DATABASE IF EXISTS app_eval WITH (FORCE)")
    n = qa["n"]
    f = lambda a: "{:.3f} | {:.3f} | {:.3f}".format(*prf(*a))      # noqa: E731
    pp, pr = qa["people_tp"] / max(1, qa["people_found"]), qa["people_tp"] / max(1, qa["people_true"])
    lines = ["# Evaluation", "",
             f"Generated by `python -m mem.evaluate` on {len(SEEDS)} synthetic archives (seeds {SEEDS[0]} to {SEEDS[-1]}, {n_art:,} records) that the demo and the tests never use.",
             "Every record is generated, so each step has a known right answer. The archives are far tidier than a real person's: read these as a check that the pipeline works, not as real-world accuracy.", "",
             "## 1. Multi-hop questions", "",
             f"{n} questions, one per restaurant dinner on a trip, in three phrasings, of the form *\"Find the Italian restaurant from my 2024 Chicago trip where I photographed a red motorcycle, then show the receipt and who I was with.\"*",
             "Each trip also contains photos sharing the colour or the object, and the same cities and cuisines recur across trips.", "",
             "| | Right restaurant | Right receipt | Everyone present, nobody extra |", "|---|---|---|---|",
             f"| Chain: trip, photo, moment, receipt, people | {qa['restaurant'] / n:.1%} | {qa['receipt'] / n:.1%} | {qa['people_exact'] / n:.1%} |",
             f"| Baseline: plain vector search for the whole question, receipts only, top 1 | | {qa['flat_receipt'] / n:.1%} | |",
             f"| Same baseline, right receipt anywhere in the top 5 | | {qa['flat_receipt5'] / n:.1%} | |", "",
             f"The chain declined to answer {qa['not_found']} of {n} questions rather than guess. People named: precision {pp:.3f}, recall {pr:.3f}.",
             f"The photo hop alone (best match for the described object across the whole archive, no trip filter) picked the right photo {qa['photo_top1'] / n:.1%} of the time: the trip filter is what makes it reliable.", "",
             "## 2. Grouping records into moments", "",
             "Pairs of records placed in the same moment, against pairs generated by the same real-world event:", "",
             "| | Precision | Recall | F1 |", "|---|---|---|---|", f"| Two-hour silence or 600 m jump | {f(mom)} |", f"| Baseline: same calendar day | {f([day[0], mom[1]])} |", "",
             "The misses are lunches that run straight into an afternoon of sightseeing, and dinners with nothing recorded between a message and the receipt.", "",
             "## 3. Linking people", "",
             "Mentions in calendar entries and messages linked to a contact card. Two contacts share a first name on purpose.", "",
             "| | Precision | Recall | F1 |", "|---|---|---|---|", f"| Rules, refusing to guess an ambiguous first name | {f(link)} |", f"| Baseline: an ambiguous first name is the first such contact | {f([naive[0], link[1]])} |", "",
             f"{unresolved} mentions were left unlinked because the first name fitted two contacts and nothing else in the moment settled it.", "",
             "## 4. Restaurants and cuisine", "",
             f"{cui[1]} restaurants were recovered from scanned receipts (merchant lines carry scanner errors such as `BELLAV1TA`); the cuisine vote was right for {cui[0]} ({cui[0] / cui[1]:.1%}).",
             "The lexicon it votes over is the same one the generator draws dishes from, so this is a check of the plumbing, not a cuisine classifier."]
    out = pathlib.Path(__file__).resolve().parent.parent / "docs" / "evaluation.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
